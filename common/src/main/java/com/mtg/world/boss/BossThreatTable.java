package com.mtg.world.boss;

import java.util.*;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Thread-safe multi-entity threat tracking engine for World Boss encounters.
 * Tracks damage, healing, and spellcasting aggro, and manages leash decay.
 */
public class BossThreatTable {
    public static final double DEFAULT_ENGAGEMENT_DISTANCE = 32.0;
    public static final double DEFAULT_LEASH_DISTANCE = 48.0;
    public static final float DEFAULT_LEASH_DECAY_RATE = 0.10f; // -10% per second

    private final Map<UUID, Float> threatScores = new ConcurrentHashMap<>();

    public BossThreatTable() {}

    /**
     * Adds threat generated by physical or spell damage dealt to the boss.
     */
    public void addDamageThreat(UUID entityId, float damage) {
        if (entityId == null || damage <= 0) return;
        threatScores.merge(entityId, damage * 1.0f, Float::sum);
    }

    /**
     * Adds threat generated by healing friendly entities in the boss's vicinity.
     */
    public void addHealingThreat(UUID entityId, float healingAmount) {
        if (entityId == null || healingAmount <= 0) return;
        threatScores.merge(entityId, healingAmount * 0.5f, Float::sum);
    }

    /**
     * Adds threat generated by casting spells in the boss's vicinity based on spell mana value.
     */
    public void addSpellThreat(UUID entityId, int manaCost) {
        if (entityId == null || manaCost <= 0) return;
        threatScores.merge(entityId, (float) manaCost * 2.0f, Float::sum);
    }

    /**
     * Directly modifies or taunts threat for an entity.
     */
    public void addThreat(UUID entityId, float threat) {
        if (entityId == null || threat == 0) return;
        threatScores.merge(entityId, threat, (curr, add) -> Math.max(0.0f, curr + add));
    }

    public float getThreat(UUID entityId) {
        if (entityId == null) return 0.0f;
        return threatScores.getOrDefault(entityId, 0.0f);
    }

    public void removeEntity(UUID entityId) {
        if (entityId != null) {
            threatScores.remove(entityId);
        }
    }

    public void clear() {
        threatScores.clear();
    }

    public Map<UUID, Float> getAllThreats() {
        return Collections.unmodifiableMap(new HashMap<>(threatScores));
    }

    /**
     * Finds the entity with the highest threat score overall.
     */
    public Optional<UUID> getHighestThreatTarget() {
        return threatScores.entrySet().stream()
                .filter(e -> e.getValue() > 0.0f)
                .max(Map.Entry.comparingByValue())
                .map(Map.Entry::getKey);
    }

    /**
     * Finds the entity with the highest threat score among entities within maximum engagement distance.
     *
     * @param entityDistances Map of entity UUID to distance from the boss
     * @param maxDistance Maximum distance (e.g. 32.0 blocks)
     * @return Optional UUID of target
     */
    public Optional<UUID> getHighestThreatTarget(Map<UUID, Double> entityDistances, double maxDistance) {
        if (entityDistances == null || entityDistances.isEmpty()) {
            return getHighestThreatTarget();
        }

        return threatScores.entrySet().stream()
                .filter(e -> e.getValue() > 0.0f)
                .filter(e -> {
                    Double dist = entityDistances.get(e.getKey());
                    return dist != null && dist <= maxDistance;
                })
                .max(Map.Entry.comparingByValue())
                .map(Map.Entry::getKey);
    }

    /**
     * Decays threat for entities that have exceeded the leash distance.
     *
     * @param entityDistances Map of entity UUID to distance from the boss
     * @param leashDistance Leash threshold (e.g. 48.0 blocks)
     * @param decayFraction Fraction to remove (e.g. 0.10f for 10% decay)
     */
    public void applyLeashDecay(Map<UUID, Double> entityDistances, double leashDistance, float decayFraction) {
        if (entityDistances == null || entityDistances.isEmpty()) return;

        for (Map.Entry<UUID, Float> entry : threatScores.entrySet()) {
            UUID entityId = entry.getKey();
            Double dist = entityDistances.get(entityId);
            if (dist != null && dist > leashDistance) {
                float newThreat = entry.getValue() * (1.0f - decayFraction);
                if (newThreat <= 0.05f) {
                    threatScores.remove(entityId);
                } else {
                    threatScores.put(entityId, newThreat);
                }
            }
        }
    }
}
